use std::convert::TryFrom;

#[derive(Debug)]
pub enum ParseSymbolError {
    UnknownSymbol(String),
}

impl TryFrom<&str> for Symbols {
    type Error = ParseSymbolError;

    fn try_from(s: &str) -> Result<Self, Self::Error> {
        // Strip the surrounding { }
        let inner = s.trim_start_matches('{').trim_end_matches('}');

        match inner {
            "T" => Ok(Symbols::Tap),
            "Q" => Ok(Symbols::Untap),
            "E" => Ok(Symbols::Energy),
            "P" => Ok(Symbols::Paw),
            "PW" => Ok(Symbols::PhyrexianWhite),
            "CHAOS" => Ok(Symbols::CHAOS),
            "A" => Ok(Symbols::Acorn),
            "TK" => Ok(Symbols::Ticket),
            "X" => Ok(Symbols::X),
            "Y" => Ok(Symbols::Y),
            "Z" => Ok(Symbols::Z),
            "0" => Ok(Symbols::Zero),
            "½" => Ok(Symbols::Half),
            "1" => Ok(Symbols::One),
            "2" => Ok(Symbols::Two),
            "3" => Ok(Symbols::Three),
            "4" => Ok(Symbols::Four),
            "5" => Ok(Symbols::Five),
            "6" => Ok(Symbols::Six),
            "7" => Ok(Symbols::Seven),
            "8" => Ok(Symbols::Eight),
            "9" => Ok(Symbols::Nine),
            "10" => Ok(Symbols::Ten),
            "11" => Ok(Symbols::Eleven),
            "12" => Ok(Symbols::Twelve),
            "13" => Ok(Symbols::Thirteen),
            "14" => Ok(Symbols::Fourteen),
            "15" => Ok(Symbols::Fifteen),
            "16" => Ok(Symbols::Sixteen),
            "17" => Ok(Symbols::Seventeen),
            "18" => Ok(Symbols::Eighteen),
            "19" => Ok(Symbols::Nineteen),
            "20" => Ok(Symbols::Twenty),
            "100" => Ok(Symbols::Hundred),
            "1000000" => Ok(Symbols::Million),
            "∞" => Ok(Symbols::Infinity),
            "W/U" => Ok(Symbols::WhiteBlue),
            "W/B" => Ok(Symbols::WhiteBlack),
            "B/R" => Ok(Symbols::BlackRed),
            "B/G" => Ok(Symbols::BlackGreen),
            "U/B" => Ok(Symbols::BlueBlack),
            "U/R" => Ok(Symbols::BlueRed),
            "R/G" => Ok(Symbols::RedGreen),
            "R/W" => Ok(Symbols::RedWhite),
            "G/W" => Ok(Symbols::GreenWhite),
            "G/U" => Ok(Symbols::GreenBlue),
            "B/G/P" => Ok(Symbols::BlackGreenPhyrexian),
            "B/R/P" => Ok(Symbols::BlackRedPhyrexian),
            "G/W/P" => Ok(Symbols::GreenWhitePhyrexian),
            "R/G/P" => Ok(Symbols::RedGreenPhyrexian),
            "R/W/P" => Ok(Symbols::RedWhitePhyrexian),
            "U/B/P" => Ok(Symbols::BlueBlack), // missing: BlueBlackPhyrexian
            "U/R/P" => Ok(Symbols::BlueRedPhyrexian),
            "W/B/P" => Ok(Symbols::WhiteBlackPhyrexian),
            "W/U/P" => Ok(Symbols::WhiteBluePhyrexian),
            "C/W" => Ok(Symbols::ColorlessWhite),
            "C/U" => Ok(Symbols::ColorlessBlue),
            "C/B" => Ok(Symbols::ColorlessBlack),
            "C/R" => Ok(Symbols::ColorlessRed),
            "C/G" => Ok(Symbols::ColorlessGreen),
            "2/W" => Ok(Symbols::TwoWhite),
            "2/U" => Ok(Symbols::TwoBlue),
            "2/B" => Ok(Symbols::TwoBlack),
            "2/R" => Ok(Symbols::TwoRed),
            "2/G" => Ok(Symbols::TwoGreen),
            "H" => Ok(Symbols::Phyrexian),
            "W/P" => Ok(Symbols::WhitePhyrexian),
            "U/P" => Ok(Symbols::BluePhyrexian),
            "B/P" => Ok(Symbols::BlackPhyrexian),
            "R/P" => Ok(Symbols::RedPhyrexian),
            "G/P" => Ok(Symbols::GreenPhyrexian),
            "C/P" => Ok(Symbols::ColorlessPhyrexian),
            "HW" => Ok(Symbols::HalfWhite),
            "HR" => Ok(Symbols::HalfRed),
            "W" => Ok(Symbols::White),
            "U" => Ok(Symbols::Blue),
            "B" => Ok(Symbols::Black),
            "R" => Ok(Symbols::Red),
            "G" => Ok(Symbols::Green),
            "C" => Ok(Symbols::Colorless),
            "S" => Ok(Symbols::Snow),
            "L" => Ok(Symbols::L),
            "D" => Ok(Symbols::D),
            _ => Err(ParseSymbolError::UnknownSymbol(s.to_string())),
        }
    }
}
